def rank(seq, value):
    return seq.index(value) if value in seq else len(seq)


def slug(name):
    return name.replace(".", "-")


def load_excluded():
    out = set()
    with open(EXCLUDED, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line and not line.startswith("#"):
                out.add(line)
    return out


def read_methods(spec):
    methods = []
    for path, item in spec["paths"].items():
        if not path.startswith("/v2/ops/") or "{" in path:
            continue
        op = item["post"]
        name = path[len("/v2/ops/"):]
        providers = op.get("x-providers", [])
        drafts = op.get("x-draft-bindings", [])
        methods.append({
            "name": name,
            "path": path,
            "summary": (op.get("summary") or "").strip(),
            "domain": name.split(".")[0],
            "platform": op.get("x-platform"),
            "action": op.get("x-action") or name.split(".", 2 if op.get("x-platform") else 1)[-1],
            "price": op.get("x-price-credits"),
            "pricing": op.get("x-pricing"),
            "providers": providers,
            "all_providers_have_drafts": bool(providers) and all(p in drafts for p in providers),
            "stability": op.get("x-stability"),
        })
    return methods


def stub_text(title, sidebar, description, method, path):
    fm = OrderedDict()
    fm["title"] = title
    if sidebar and sidebar != title:
        fm["sidebarTitle"] = sidebar
    if description:
        fm["description"] = description
    fm["openapi"] = f"{SPEC_REF} {method} {path}"
    lines = ["---"]
    for k, v in fm.items():
        lines.append(f"{k}: {json.dumps(v, ensure_ascii=False)}")
    lines += ["---", "", MARKER, ""]
    return "\n".join(lines)


def write_stub(rel, text, written):
    dst = os.path.join(STUB_DIR, rel)
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    with open(dst, "w", encoding="utf-8") as f:
        f.write(text)
    written.add(os.path.normpath(dst))


def page_ref(rel):
    return "api-reference/scenario/methods/" + rel[:-len(".mdx")]


def build(spec, methods, excluded):
    written = set()
    public = [m for m in methods if m["name"] not in excluded]

    # Catalog & describe endpoints.
    catalog_pages = []
    cat_op = spec["paths"]["/v2/ops"]["get"]
    write_stub("catalog.mdx", stub_text("List methods", "List methods", (cat_op.get("summary") or "").strip(), "GET", "/v2/ops"), written)
    catalog_pages.append(page_ref("catalog.mdx"))
    desc_op = spec["paths"]["/v2/ops/{op}"]["get"]
    write_stub("describe.mdx", stub_text("Describe a method", "Describe a method", (desc_op.get("summary") or "").strip(), "GET", "/v2/ops/{op}"), written)
    catalog_pages.append(page_ref("describe.mdx"))

    # Methods grouped by domain, then platform.
    groups = []
    for domain in sorted({m["domain"] for m in public}, key=lambda d: rank(DOMAIN_ORDER, d)):
        dm = [m for m in public if m["domain"] == domain]
        platforms = sorted({m["platform"] for m in dm if m["platform"]}, key=lambda p: (rank(PLATFORM_ORDER, p), p))
        if platforms:
            sub = []
            for p in platforms:
                pm = sorted([m for m in dm if m["platform"] == p], key=lambda m: (rank(ACTION_ORDER, m["action"]), m["name"]))
                pages = []
                for m in pm:
                    rel = slug(m["name"]) + ".mdx"
                    write_stub(rel, stub_text(m["name"], m["action"], m["summary"], "POST", m["path"]), written)
                    pages.append(page_ref(rel))
                sub.append({"group": PLATFORM_TITLE.get(p, p.replace("_", " ").title()), "pages": pages})
            # non-platform methods inside a platform domain (none today, kept for safety)
            rest = sorted([m for m in dm if not m["platform"]], key=lambda m: m["name"])
            for m in rest:
                rel = slug(m["name"]) + ".mdx"
                write_stub(rel, stub_text(m["name"], m["name"].split(".", 1)[1], m["summary"], "POST", m["path"]), written)
                sub.append(page_ref(rel))
            groups.append({"group": DOMAIN_TITLE.get(domain, domain.title()), "pages": sub})
        else:
            pages = []
            for m in sorted(dm, key=lambda m: m["name"]):
                rel = slug(m["name"]) + ".mdx"
                write_stub(rel, stub_text(m["name"], m["name"].split(".", 1)[1], m["summary"], "POST", m["path"]), written)
                pages.append(page_ref(rel))
            groups.append({"group": DOMAIN_TITLE.get(domain, domain.title()), "pages": pages})

    # Remove stale generated stubs.
    removed = 0
    for dirpath, _, files in os.walk(STUB_DIR):
        for fn in files:
            full = os.path.normpath(os.path.join(dirpath, fn))
            if full in written or not fn.endswith(".mdx"):
                continue
            with open(full, encoding="utf-8") as f:
                if MARKER in f.read():
                    os.remove(full)
                    removed += 1
    return catalog_pages, groups, len(public), removed


def update_docs_json(catalog_pages, groups):
    with open(DOCS_JSON, encoding="utf-8") as f:
        docs = json.load(f, object_pairs_hook=OrderedDict)
    tabs = docs["navigation"]["tabs"]
    tab = next((t for t in tabs if t.get("tab") == TAB_NAME), None)
    if tab is None:
        sys.exit(f"docs.json: tab {TAB_NAME!r} not found")
    new_catalog = OrderedDict([("group", "Catalog & Describe"), ("pages", catalog_pages)])
    new_methods = OrderedDict([("group", "Methods"), ("pages", groups)])
    out = []
    replaced = {"Catalog & Describe": False, "Methods": False}
    for g in tab["groups"]:
        if g.get("group") == "Catalog & Describe":
            out.append(new_catalog); replaced["Catalog & Describe"] = True
        elif g.get("group") == "Methods":
            out.append(new_methods); replaced["Methods"] = True
        else:
            out.append(g)
    # If missing, insert after the "Scenario Methods" guide group (or append).
    def insert_after(name, item):
        idx = next((i for i, g in enumerate(out) if g.get("group") == name), None)
        if idx is None:
            out.append(item)
        else:
            out.insert(idx + 1, item)
    if not replaced["Catalog & Describe"]:
        insert_after("Scenario Methods", new_catalog)
    if not replaced["Methods"]:
        insert_after("Catalog & Describe", new_methods)
    tab["groups"] = out
    with open(DOCS_JSON, "w", encoding="utf-8") as f:
        json.dump(docs, f, indent=2, ensure_ascii=False)
        f.write("\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--server-repo", default=os.environ.get("AGENTKEY_SERVER_REPO"), help="path to the AgentKey-Server checkout")
    args = ap.parse_args()
    if not args.server_repo:
        ap.error("--server-repo (or AGENTKEY_SERVER_REPO) is required")
    src = os.path.join(args.server_repo, "docs", "openapi", "v2.yaml")
    if not os.path.isfile(src):
        sys.exit(f"snapshot not found: {src}")
    os.makedirs(os.path.dirname(SPEC_DST), exist_ok=True)
    shutil.copyfile(src, SPEC_DST)
    with open(SPEC_DST, encoding="utf-8") as f:
        spec = yaml.safe_load(f)
    methods = read_methods(spec)
    excluded = load_excluded()
    unknown = excluded - {m["name"] for m in methods}
    if unknown:
        print("warning: excluded names not in the snapshot:", ", ".join(sorted(unknown)))
    suspicious = [m["name"] for m in methods if m["all_providers_have_drafts"] and m["name"] not in excluded]
    catalog_pages, groups, n_public, removed = build(spec, methods, excluded)
    update_docs_json(catalog_pages, groups)
    print(f"snapshot: {len(methods)} methods, {n_public} public, {len(excluded)} excluded, {removed} stale stub(s) removed")
    print(f"spec copied to {os.path.relpath(SPEC_DST, ROOT)}; stubs in {os.path.relpath(STUB_DIR, ROOT)}; docs.json updated")
    if suspicious:
        print("verify (every provider has at least one draft binding; may or may not be routable):")
        for n in suspicious:
            print("  -", n)


if __name__ == "__main__":
    main()
