#!/usr/bin/env python3
"""Sync the Scenario Methods OpenAPI snapshot from the AgentKey server repo.

What it does:
  1. Copies <server-repo>/docs/openapi/v2.yaml to api-reference/openapi/v2.yaml
     byte for byte.
  2. Writes one MDX stub per public method into api-reference/scenario/methods/
     (frontmatter `openapi:` points at the operation, Mintlify renders the page).
     Methods listed in scripts/scenario-excluded.txt are skipped.
  3. Rewrites the "Methods" and "Catalog & Describe" groups of the API Reference
     tab in docs.json so the sidebar matches the stubs.

Usage:
  python3 scripts/sync-openapi.py --server-repo ../path/to/AgentKey-Server
  (or set AGENTKEY_SERVER_REPO)

Requires Python 3 and PyYAML.
"""
import argparse, json, os, re, shutil, sys
from collections import OrderedDict

try:
    import yaml
except ImportError:  # pragma: no cover
    sys.exit("PyYAML is required: pip install pyyaml")

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SPEC_DST = os.path.join(ROOT, "api-reference", "openapi", "v2.yaml")
STUB_DIR = os.path.join(ROOT, "api-reference", "scenario", "methods")
EXCLUDED = os.path.join(ROOT, "scripts", "scenario-excluded.txt")
DOCS_JSON = os.path.join(ROOT, "docs.json")
MARKER = "{/* Generated by scripts/sync-openapi.py from the server's OpenAPI snapshot. Do not edit by hand. */}"
SPEC_REF = "/api-reference/openapi/v2.yaml"
TAB_NAME = "API Reference"

